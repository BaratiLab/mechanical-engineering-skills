#!/usr/bin/env python3
"""Family case builders: request spec -> resolved spec (with provenance) -> OpenFOAM case.

  spec          python build_case.py spec --family forward-step-2d --stated stated.json --out spec.json
  forward-step  python build_case.py forward-step --spec spec.json --case cases/m2 [--template $FOAM_TUTORIALS/shockFluid/forwardStep]
  nozzle        python build_case.py nozzle --spec spec.json --case cases/noz [--template $FOAM_TUTORIALS/shockFluid/forwardStep]
  recipe-hash   python build_case.py recipe-hash --case cases/m2 [--expect sha]

The agent writes only stated.json (values the request states; nothing guessed). Every
other value comes from the family defaults, and spec.json records which is which.
Builders copy the numerical recipe from a template, record its SHA-256, and write
blockMeshDict with outward-oriented faces generated from the canonical hex topology.
Numerics/BC formulations are fixed by the family: requests change values, not formulations.
"""
import argparse
import hashlib
import json
import math
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import contracts as C  # noqa: E402

RECIPE_FILES = ["system/fvSchemes", "system/fvSolution", "constant/physicalProperties",
                "constant/momentumTransport"]
HEX_FACES = [(0, 4, 7, 3), (1, 2, 6, 5), (0, 1, 5, 4), (3, 7, 6, 2), (0, 3, 2, 1), (4, 5, 6, 7)]
XMIN, XMAX, YMIN, YMAX, ZMIN, ZMAX = range(6)
HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by me-design-skills/cfd-simulation-setup ({family} v{ver})
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    format      ascii;
    class       {cls};
    object      {obj};
}}
"""


# ----------------------------------------------------------------- spec
def resolve(family, stated):
    c = C.get(family)
    resolved, prov = {}, {}
    for k, v in c["defaults"].items():
        if stated.get(k) is not None:
            resolved[k], prov[k] = stated[k], "stated_by_user"
        else:
            resolved[k], prov[k] = v, "inferred_from_family_defaults"
    extra = {k: v for k, v in stated.items() if k not in c["defaults"] and v is not None}
    for k, v in extra.items():
        if k in c["envelope"] or k in ("requests_unsupported_physics", "request_criteria", "reporting_objectives", "case_name"):
            resolved[k], prov[k] = v, "stated_by_user"
        else:
            prov[k] = "IGNORED_not_a_family_parameter"
    return {"family": family, "contract_version": c["version"], "resolved": resolved, "provenance": prov}


# ----------------------------------------------------------------- blockMesh writer
class BlockMesh:
    def __init__(self):
        self.pts, self.blocks, self.patches = [], [], {}

    def pt(self, p):
        for i, q in enumerate(self.pts):
            if all(abs(a - b) < 1e-12 for a, b in zip(p, q)):
                return i
        self.pts.append(tuple(p))
        return len(self.pts) - 1

    def block(self, verts8, cells):
        self.blocks.append(([self.pt(v) for v in verts8], cells))
        return len(self.blocks) - 1

    def patch(self, name, ptype, faces):
        self.patches.setdefault(name, (ptype, []))[1].extend(faces)

    def face(self, b, f):
        v = self.blocks[b][0]
        return tuple(v[i] for i in HEX_FACES[f])

    def write(self, path, family, ver):
        L = [HEADER.format(family=family, ver=ver, cls="dictionary", obj="blockMeshDict"), "convertToMeters 1;\n\nvertices\n("]
        L += [f"    ({x:.10g} {y:.10g} {z:.10g})" for x, y, z in self.pts]
        L += [");\n\nblocks\n("]
        L += [f"    hex ({' '.join(map(str, v))}) ({' '.join(map(str, c))}) simpleGrading (1 1 1)" for v, c in self.blocks]
        L += [");\n\nedges\n(\n);\n\nboundary\n("]
        for name, (ptype, faces) in self.patches.items():
            L.append(f"    {name}\n    {{\n        type {ptype};\n        faces\n        (")
            L += [f"            ({' '.join(map(str, self.face(b, f)))})" for b, f in faces]
            L.append("        );\n    }")
        L.append(");\n\nmergePatchPairs\n(\n);\n")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write("\n".join(L))

    def ncells(self):
        return sum(math.prod(c) for _, c in self.blocks)


def rect(bm, x0, x1, y0, y1, z0, z1, nx, ny):
    v = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
         (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    return bm.block(v, (nx, ny, 1))


# ----------------------------------------------------------------- template / hash
def copy_template(template, case):
    if template and os.path.isdir(template):
        if os.path.exists(case):
            shutil.rmtree(case)
        shutil.copytree(template, case)
        return True
    os.makedirs(case, exist_ok=True)
    return False


def recipe_hash(case):
    h = hashlib.sha256()
    found = []
    for f in RECIPE_FILES:
        p = os.path.join(case, f)
        if os.path.exists(p):
            h.update(f.encode()); h.update(open(p, "rb").read()); found.append(f)
    return h.hexdigest(), found


# ----------------------------------------------------------------- forward step
def build_forward_step(spec, case, template):
    r = spec["resolved"]
    L, H, h, xs, dx = r["length"], r["height"], r["step_height"], r["step_x"], r["dx"]
    n = lambda d: max(1, round(d / dx))
    zb, zf = -0.05, 0.05
    bm = BlockMesh()
    a = rect(bm, 0, xs, 0, h, zb, zf, n(xs), n(h))            # below step height, upstream
    b = rect(bm, 0, xs, h, H, zb, zf, n(xs), n(H - h))        # above, upstream
    c = rect(bm, xs, L, h, H, zb, zf, n(L - xs), n(H - h))    # above step
    bm.patch("inlet", "patch", [(a, XMIN), (b, XMIN)])
    bm.patch("outlet", "patch", [(c, XMAX)])
    bm.patch("bottom", "symmetryPlane", [(a, YMIN)])
    bm.patch("top", "symmetryPlane", [(b, YMAX), (c, YMAX)])
    bm.patch("obstacle", "patch", [(a, XMAX), (c, YMIN)])
    had_template = copy_template(template, case)
    u0 = os.path.join(case, "0", "U")
    utxt = open(u0).read() if os.path.exists(u0) else ""
    empty_name = "frontAndBack" if "frontAndBack" in utxt else "defaultFaces"
    bm.patch(empty_name, "empty", [(i, f) for i in (a, b, c) for f in (ZMIN, ZMAX)])
    pre_hash, files = recipe_hash(case)
    bm.write(os.path.join(case, "system/blockMeshDict"), "forward-step-2d", spec["contract_version"])
    missing = [n for n in bm.patches if utxt and n not in utxt]
    M, E, Co = r["mach"], r["end_time"], r["max_co"]
    sh = f"""#!/bin/bash
# Generated case setup: forward-step-2d. Values only; formulations come from the template recipe.
set -e
cd "$(dirname "$0")"
foamDictionary 0/U -entry internalField -set "uniform ({M} 0 0)"
foamDictionary 0/U -entry boundaryField/inlet/value -set "uniform ({M} 0 0)"
foamDictionary 0/p -entry internalField -set "uniform {r['pressure']}"
foamDictionary 0/T -entry internalField -set "uniform {r['temperature']}"
foamDictionary system/controlDict -entry endTime -set {E}
foamDictionary system/controlDict -entry maxCo -set {Co}
foamDictionary system/controlDict -entry writeInterval -set {r['write_interval']}
blockMesh > log.blockMesh 2>&1
checkMesh > log.checkMesh 2>&1
foamRun > log.foamRun 2>&1
"""
    open(os.path.join(case, "Allrun.agent"), "w").write(sh)
    os.chmod(os.path.join(case, "Allrun.agent"), 0o755)
    rec = {"family": "forward-step-2d", "cells": bm.ncells(), "dx": dx, "template_copied": had_template,
           "patches_missing_in_template_fields": missing,
           "recipe_sha256": pre_hash, "recipe_files": files,
           "inlet_U": [M, 0, 0], "note": "normalized gas: sound speed 1 at T=1, so |U| = Mach"}
    json.dump(rec | {"spec": spec}, open(os.path.join(case, "case_record.json"), "w"), indent=2)
    return rec


# ----------------------------------------------------------------- nozzle (axisymmetric wedge)
def nozzle_stations(r):
    if "stations" in r:
        return r["stations"]
    ri, rt, re_, Lz = r["r_inlet_m"], r["r_throat_m"], r["r_exit_m"], r["length_m"]
    # skill-default contour: straight inlet, cone to throat, short throat, cone to exit, straight exit
    xs = [0, 0.15, 0.45, 0.48, 0.94, 1.0]
    rs = [ri, ri, rt, rt, re_, re_]
    return [(x * Lz, y) for x, y in zip(xs, rs)]


def build_nozzle(spec, case, template):
    r = spec["resolved"]
    st = nozzle_stations(r)
    th = math.radians(r["wedge_deg"]) / 2
    nax, nr = r["axial_cells"], r["radial_cells"]
    if len(nax) != len(st) - 1:
        raise SystemExit("axial_cells must have one entry per segment between stations")
    bm = BlockMesh()
    ids = []
    for i in range(len(st) - 1):
        (x0, r0), (x1, r1) = st[i], st[i + 1]
        v = [(x0, 0, 0), (x1, 0, 0), (x1, r1 * math.cos(th), -r1 * math.sin(th)), (x0, r0 * math.cos(th), -r0 * math.sin(th)),
             (x0, 0, 0), (x1, 0, 0), (x1, r1 * math.cos(th), r1 * math.sin(th)), (x0, r0 * math.cos(th), r0 * math.sin(th))]
        ids.append(bm.block(v, (nax[i], nr, 1)))
    bm.patch("inlet", "patch", [(ids[0], XMIN)])
    bm.patch("outlet", "patch", [(ids[-1], XMAX)])
    bm.patch("wall", "wall", [(b, YMAX) for b in ids])
    bm.patch("axis", "empty", [(b, YMIN) for b in ids])
    bm.patch("front", "wedge", [(b, ZMAX) for b in ids])
    bm.patch("back", "wedge", [(b, ZMIN) for b in ids])
    had_template = copy_template(template, case)
    bm.write(os.path.join(case, "system/blockMeshDict"), "cd-nozzle", spec["contract_version"])
    p0, T0, g = r["p0_Pa"], r["T0_K"], r["gamma"]
    patches_common = """    front  { type wedge; }
    back   { type wedge; }
    axis   { type empty; }"""
    fields = {
        "p": ("volScalarField", "[1 -1 -2 0 0 0 0]", f"uniform {p0}",
              f"""    inlet  {{ type totalPressure; p0 uniform {p0}; psi thermo:psi; gamma {g}; value uniform {p0}; }}
    outlet {{ type zeroGradient; }}
    wall   {{ type zeroGradient; }}
{patches_common}"""),
        "T": ("volScalarField", "[0 0 0 1 0 0 0]", f"uniform {T0}",
              f"""    inlet  {{ type totalTemperature; T0 uniform {T0}; gamma {g}; value uniform {T0}; }}
    outlet {{ type zeroGradient; }}
    wall   {{ type zeroGradient; }}
{patches_common}"""),
        "U": ("volVectorField", "[0 1 -1 0 0 0 0]", "uniform (0 0 0)",
              f"""    inlet  {{ type pressureDirectedInletVelocity; inletDirection uniform (1 0 0); value uniform (0 0 0); }}
    outlet {{ type zeroGradient; }}
    wall   {{ type slip; }}
{patches_common}"""),
    }
    os.makedirs(os.path.join(case, "0"), exist_ok=True)
    for name in list(os.listdir(os.path.join(case, "0"))):
        os.remove(os.path.join(case, "0", name))  # template fields have the wrong patches
    for name, (cls, dim, internal, bcs) in fields.items():
        txt = HEADER.format(family="cd-nozzle", ver=spec["contract_version"], cls=cls, obj=name)
        txt += f"\ndimensions      {dim};\n\ninternalField   {internal};\n\nboundaryField\n{{\n{bcs}\n}}\n"
        open(os.path.join(case, "0", name), "w").write(txt)
    sh = f"""#!/bin/bash
# Generated case setup: cd-nozzle. Air, inviscid. Reconstruction per family recipe: {r['reconstruction']}.
set -e
cd "$(dirname "$0")"
foamDictionary constant/physicalProperties -entry mixture/specie/molWeight -set 28.96
foamDictionary constant/physicalProperties -entry mixture/thermodynamics/Cp -set 1004.5
foamDictionary constant/physicalProperties -entry mixture/transport/mu -set 0
foamDictionary system/fvSchemes -entry interpolationSchemes/"reconstruct(rho)" -set "{r['reconstruction']}"
foamDictionary system/fvSchemes -entry interpolationSchemes/"reconstruct(U)" -set "{r['reconstruction']}V"
foamDictionary system/fvSchemes -entry interpolationSchemes/"reconstruct(T)" -set "{r['reconstruction']}"
foamDictionary system/controlDict -entry endTime -set {r['end_time_s']}
foamDictionary system/controlDict -entry maxCo -set {r['max_co']}
blockMesh > log.blockMesh 2>&1
checkMesh > log.checkMesh 2>&1
foamRun > log.foamRun 2>&1
"""
    open(os.path.join(case, "Allrun.agent"), "w").write(sh)
    os.chmod(os.path.join(case, "Allrun.agent"), 0o755)
    rec = {"family": "cd-nozzle", "cells": bm.ncells(), "stations": st, "template_copied": had_template,
           "note": "After the foamDictionary edits run `build_case.py recipe-hash` and store the hash; "
                   "the contour is a skill default unless 'stations' was stated."}
    json.dump(rec | {"spec": spec}, open(os.path.join(case, "case_record.json"), "w"), indent=2)
    return rec


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("spec"); s.add_argument("--family", required=True); s.add_argument("--stated", required=True); s.add_argument("--out", required=True)
    for name in ("forward-step", "nozzle"):
        s = sub.add_parser(name); s.add_argument("--spec", required=True); s.add_argument("--case", required=True)
        s.add_argument("--template", default=os.path.expandvars("$FOAM_TUTORIALS/shockFluid/forwardStep"))
    s = sub.add_parser("recipe-hash"); s.add_argument("--case", required=True); s.add_argument("--expect")
    a = ap.parse_args()
    if a.cmd == "spec":
        r = resolve(a.family, json.load(open(a.stated)))
        json.dump(r, open(a.out, "w"), indent=2)
    elif a.cmd == "forward-step":
        r = build_forward_step(json.load(open(a.spec)), a.case, a.template)
    elif a.cmd == "nozzle":
        r = build_nozzle(json.load(open(a.spec)), a.case, a.template)
    else:
        hsh, files = recipe_hash(a.case)
        r = {"recipe_sha256": hsh, "files": files}
        if a.expect:
            r["checks"] = {"recipe_hash_ok": hsh == a.expect}
    print(json.dumps(r, indent=2, default=list))


if __name__ == "__main__":
    main()
